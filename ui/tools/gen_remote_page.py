"""Build ui/remote_page.c (the Remote Control web pages) from ui/remote_page/.

remote.html (Now playing, queue, library) and system.html (Status, Bluetooth, Screen) each contain the markers
@@STYLE@@ (style.css) and @@COMMON@@ (common.js), which are pasted in, so every page is one self-contained file
(the server sends no other files and the Content-Security-Policy allows inline code only).

    python3 ui/tools/gen_remote_page.py           write ui/remote_page.c
    python3 ui/tools/gen_remote_page.py --check   exit 1 if ui/remote_page.c is not up to date
"""
import os
import sys

UI = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(UI, 'remote_page')
OUT = os.path.join(UI, 'remote_page.c')
PAGES = [('RMT_PAGE_HTML', 'remote.html'), ('RMT_SYS_HTML', 'system.html')]


def read(name):
    with open(os.path.join(SRC, name), encoding='utf-8') as f:
        return f.read()


def c_lines(text):
    out = []
    for line in text.rstrip('\n').split('\n'):
        esc = line.replace('\\', '\\\\').replace('"', '\\"').replace('??', '?\\?')
        out.append('"' + esc + '\\n"')
    return '\n'.join(out)


def build():
    style, common = read('style.css').rstrip('\n'), read('common.js').rstrip('\n')
    parts = ['/* SPDX-License-Identifier: GPL-3.0-or-later */',
             '/* Copyright (C) 2026 diskOS contributors */',
             '/* GENERATED by ui/tools/gen_remote_page.py from ui/remote_page/ - edit those files, then run it. */',
             '#include "remote_core.h"', '']
    for sym, name in PAGES:
        page = read(name)
        if page.count('@@STYLE@@') != 1 or page.count('@@COMMON@@') != 1:
            sys.exit('%s: needs @@STYLE@@ and @@COMMON@@ exactly once' % name)
        page = page.replace('@@STYLE@@', style).replace('@@COMMON@@', common)
        parts.append('const char %s[] =\n%s;\n' % (sym, c_lines(page)))
    return '\n'.join(parts)


def main():
    text = build()
    if '--check' in sys.argv[1:]:
        try:
            with open(OUT, encoding='utf-8') as f:
                same = f.read() == text
        except OSError:
            same = False
        if not same:
            sys.exit('ui/remote_page.c is out of date: run python3 ui/tools/gen_remote_page.py')
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)


if __name__ == '__main__':
    main()
